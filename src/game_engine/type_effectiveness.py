TYPE_TO_INDEX = {name: idx for idx, name in enumerate(TYPE_NAMES)}


def get_effectiveness(move_type: str, defender_types: list[str]) -> float:
    move_idx = TYPE_TO_INDEX[move_type]
    multiplier = 1.0
    for t in defender_types:
        def_idx = TYPE_TO_INDEX[t]
        multiplier *= EFFECTIVENESS_MATRIX[def_idx][move_idx]
    return multiplier
